CREATE TABLE notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    destinatario VARCHAR(150) NOT NULL,
    assunto VARCHAR(200) NOT NULL,
    mensagem TEXT NOT NULL,
    tentativas INTEGER NOT NULL DEFAULT 0,
    proxima_tentativa TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviada_em TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notificacoes_pendentes ON notificacoes(enviada_em, proxima_tentativa);
CREATE TABLE aprovacoes_externas (
    evento_id UUID PRIMARY KEY,
    ordem_id BIGINT NOT NULL REFERENCES ordens_servico(id),
    versao_orcamento BIGINT NOT NULL,
    aprovada BOOLEAN NOT NULL,
    observacao VARCHAR(500),
    recebida_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (ordem_id, versao_orcamento)
);
