CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(14) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(150) NOT NULL,
    CONSTRAINT uk_cliente_cpf_cnpj UNIQUE (cpf_cnpj),
    CONSTRAINT uk_cliente_email UNIQUE (email)
);

CREATE TABLE itens_peca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL,
    peca_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(12,2) NOT NULL
);

CREATE TABLE itens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ordem_servico_id BIGINT NOT NULL,
    servico_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(12,2) NOT NULL
);

CREATE TABLE ordens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_os VARCHAR(30) NOT NULL UNIQUE,
    cliente_id BIGINT NOT NULL,
    veiculo_id BIGINT NOT NULL,
    status_aprovacao_orcamento VARCHAR(30),
    data_aprovacao_orcamento TIMESTAMP(6),
    observacao_aprovacao_orcamento VARCHAR(500),
    status VARCHAR(30) NOT NULL,
    valor_total NUMERIC(12,2) NOT NULL,
    observacoes VARCHAR(1000),
    data_criacao TIMESTAMP(6) NOT NULL,
    data_envio_orcamento TIMESTAMP(6),
    data_aprovacao TIMESTAMP(6),
    data_inicio_execucao TIMESTAMP(6),
    data_finalizacao TIMESTAMP(6),
    data_entrega TIMESTAMP(6),
    data_cancelamento TIMESTAMP(6),
    estoque_baixado BOOLEAN NOT NULL,
    data_baixa_estoque TIMESTAMP(6),
    estoque_devolvido BOOLEAN NOT NULL,
    data_devolucao_estoque TIMESTAMP(6),
    CONSTRAINT uk_ordem_servico_numero UNIQUE (numero_os)
);

CREATE TABLE pecas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT,
    codigo VARCHAR(50) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(500),
    valor NUMERIC(12,2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL,
    CONSTRAINT uk_peca_codigo UNIQUE (codigo)
);

CREATE TABLE servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(500),
    valor NUMERIC(12,2) NOT NULL,
    tempo_estimado_minutos INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(150) NOT NULL,
    senha VARCHAR(100) NOT NULL,
    perfil VARCHAR(30) NOT NULL,
    ativo BOOLEAN NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE veiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR(7) NOT NULL,
    marca VARCHAR(100) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    ano INTEGER NOT NULL,
    cliente_id BIGINT NOT NULL,
    CONSTRAINT uk_veiculo_placa UNIQUE (placa)
);

