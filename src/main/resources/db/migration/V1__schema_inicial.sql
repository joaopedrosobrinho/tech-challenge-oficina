ALTER TABLE itens_peca ADD CONSTRAINT fk_item_peca_peca FOREIGN KEY (peca_id) REFERENCES pecas(id);
ALTER TABLE itens_servico ADD CONSTRAINT fk_item_servico_os FOREIGN KEY (ordem_servico_id) REFERENCES ordens_servico(id);
ALTER TABLE itens_servico ADD CONSTRAINT fk_item_servico_servico FOREIGN KEY (servico_id) REFERENCES servicos(id);
ALTER TABLE ordens_servico ADD CONSTRAINT fk_os_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id);
ALTER TABLE ordens_servico ADD CONSTRAINT fk_os_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculos(id);
ALTER TABLE veiculos ADD CONSTRAINT fk_veiculo_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id);

